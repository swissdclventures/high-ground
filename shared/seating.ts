/** Length of every seated clip (scripts/emotes/build-seat-poses.ts). Re-fire on this seam. */
export const SEAT_POSE_LOOP_S = 4;

/**
 * Solved hip-BONE height above the paving — the LOWEST of the four poses, which is the one the
 * bench has to fit (a pose that solves higher floats a few millimetres and nobody notices; one
 * that solves lower has the slab cutting through it).
 * ‼️ Regenerated by `npm run build:seat-poses` — copy the number it prints.
 */
export const SEAT_HIP_HEIGHT_M = 0.536;

/**
 * ★★ THE HIP BONE IS NOT THE PART THAT TOUCHES THE BENCH, AND THAT COST US A VERSION.
 * The first bench modelled its top 60 mm under the hip BONE, which on the DCL rig is 60 mm
 * ABOVE the mid-thigh line — so the slab ran through the sitter's legs and it read in-world as
 * sinking into the seat. Both numbers below are measured off the base body
 * (`output/l1-wearable-cache/.../BaseMale.glb`), not guessed:
 *
 *   hip bone y=1.000 → hip socket y=0.937               = 0.063 down
 *   hip socket      → lowest rear vertex of the pelvis  = 0.121 down
 *
 * The seated thigh's underside lands ~0.10 below the socket, i.e. 20 mm ABOVE the buttocks, so
 * modelling to the buttocks seats the guest and leaves the thighs just clear of the slab.
 */
export const HIP_SOCKET_DROP_M = 0.063;
const BUTTOCK_DROP_M = 0.121;

/** Hip BONE down to whatever the guest is sitting on. */
export const SEATED_UNDERSIDE_DROP_M = HIP_SOCKET_DROP_M + BUTTOCK_DROP_M;

/**
 * Half the thigh, front to back (BaseMale's mid-thigh measures 0.20 m across). A seated thigh
 * is horizontal, so this is how far its underside hangs below the leg bone — and therefore the
 * clearance the slab has to leave. Exported because the pose tests assert against it.
 */
export const SEATED_THIGH_HALF_M = 0.1;

/** Top face of the bench seat. Everything else about the bench hangs off this. */
export const BENCH_SEAT_TOP_M = SEAT_HIP_HEIGHT_M - SEATED_UNDERSIDE_DROP_M;

/**
 * Bench finishes. `halo` is the default — a graphite slab that appears to float on one lit
 * pedestal. `prism` is the same shape in pale backlit white, for plazas where black furniture
 * reads as a hole in the paving. `timber` is the original warm bench, kept for parks.
 */
export const SEATING_STYLE_IDS = ["halo", "prism", "timber"] as const;
export type SeatingStyleId = (typeof SEATING_STYLE_IDS)[number];

export const SEATING_STYLE_LABELS: Record<SeatingStyleId, string> = {
  halo: "Halo — graphite + light",
  prism: "Prism — pale + backlit",
  timber: "Timber — warm bench",
};

export const DEFAULT_SEAT_GLOW = "#4de1ff";

export function isSeatingStyleId(v: unknown): v is SeatingStyleId {
  return typeof v === "string" && (SEATING_STYLE_IDS as readonly string[]).includes(v);
}

export function isSeatPoseId(v: unknown): v is SeatPoseId {
  return typeof v === "string" && (SEAT_POSE_IDS as readonly string[]).includes(v);
}

/* ------------------------------------------------------------------ config -- */

/** Bench circles spread over the plot paving. Persisted on `SiteGroundConfig.seating`. */
export interface SeatingConfig {
  enabled: boolean;
  /** How many bench circles to place. Trimmed by spacing, exclusions and the plot size. */
  clusters: number;
  /** Benches per circle. Three reads as a conversation; two as a waiting room. */
  benchesPerCluster: number;
  /** Distance from the circle's centre to each bench's seat line. */
  radiusM: number;
  /** Which finish the benches and the beacon wear. */
  style: SeatingStyleId;
  /** #rrggbb of every light strip on the bench and the beacon. */
  glowColor: string;
  /** A lit beacon in the middle, so the circle reads as a place rather than stray furniture. */
  centrepiece: boolean;
  /** Keep this far clear of the plot edge. */
  edgeMarginM: number;
  /** Extra keep-out padding around every building. */
  clearanceM: number;
  /** Minimum centre-to-centre distance between two circles. */
  spacingM: number;
  /** Changing this reshuffles where the circles land without touching anything else. */
  seed: number;
  /** Poses offered on a seat, in order. The first is what a plain click plays. */
  poses: SeatPoseId[];
}

export const SEATING_MAX_CLUSTERS = 12;
export const SEATING_MAX_BENCHES_PER_CLUSTER = 6;

export function defaultSeatingConfig(): SeatingConfig {
  return {
    enabled: false,
    clusters: 3,
    benchesPerCluster: 3,
    radiusM: 2.4,
    style: "halo",
    glowColor: DEFAULT_SEAT_GLOW,
    centrepiece: true,
    edgeMarginM: 4,
    clearanceM: 2.5,
    spacingM: 14,
    seed: 1,
    poses: [...SEAT_POSE_IDS],
  };
}

function num(raw: unknown, fallback: number, lo: number, hi: number): number {
  const v = typeof raw === "number" && Number.isFinite(raw) ? raw : fallback;
  return Math.min(hi, Math.max(lo, v));
}

/** Anything that is not a #rrggbb falls back — a stray value must not paint a bench black. */
function hexColor(raw: unknown, fallback: string): string {
  return typeof raw === "string" && /^#[0-9a-fA-F]{6}$/.test(raw) ? raw.toLowerCase() : fallback;
}

/** Unknown/old shapes fall back to the default — a bad config must never brick a recipe. */
export function normalizeSeatingConfig(raw: unknown): SeatingConfig {
  const base = defaultSeatingConfig();
  if (!raw || typeof raw !== "object") return base;
  const o = raw as Record<string, unknown>;
  const poses = Array.isArray(o.poses) ? o.poses.filter(isSeatPoseId) : [];
  return {
    enabled: o.enabled === true,
    clusters: Math.round(num(o.clusters, base.clusters, 0, SEATING_MAX_CLUSTERS)),
    benchesPerCluster: Math.round(
      num(o.benchesPerCluster, base.benchesPerCluster, 1, SEATING_MAX_BENCHES_PER_CLUSTER),
    ),
    radiusM: num(o.radiusM, base.radiusM, 1.4, 12),
    style: isSeatingStyleId(o.style) ? o.style : base.style,
    glowColor: hexColor(o.glowColor, base.glowColor),
    centrepiece: o.centrepiece !== false,
    edgeMarginM: num(o.edgeMarginM, base.edgeMarginM, 0, 200),
    clearanceM: num(o.clearanceM, base.clearanceM, 0, 100),
    spacingM: num(o.spacingM, base.spacingM, 0, 200),
    seed: Math.round(num(o.seed, base.seed, 0, 1_000_000)),
    // An empty list would leave a seat with nothing to play, so it falls back to all four.
    poses: poses.length > 0 ? SEAT_POSE_IDS.filter((id) => poses.includes(id)) : [...SEAT_POSE_IDS],
  };
}

/* ---------------------------------------------------------------- geometry -- */

export const BENCH_LENGTH_M = 1.8;
export const BENCH_DEPTH_M = 0.52;
const SEAT_SLAB_THICKNESS_M = 0.07;
/**
 * ★ THE BACK IS SIZED TO THE ARMS, NOT TO A CATALOGUE. `seat_arms_back` solves its forearms to
 * y≈0.89 with the underside ~0.05 lower, so the rail's TOP goes at 0.84 and the arm lies along
 * it. Move this and that pose drapes over thin air.
 */
const BACK_TOP_M = 0.84;
const BACK_THICKNESS_M = 0.07;
/** Height of the top rail the "arms on the back" pose drapes over. */
const BACK_RAIL_M = 0.1;
export const SEATS_PER_BENCH = 3;
/** Seat anchors sit this far apart along the bench. Two avatars any closer visibly overlap. */
const SEAT_PITCH_M = 0.6;

/**
 * How far forward of the seat ANCHOR the slab still runs. Past this the sitter's legs are out
 * over the paving and may hang wherever the pose wants — the pose tests use it to decide which
 * part of a leg has to clear the seat.
 */
export const SEAT_SLAB_REACH_M = BENCH_DEPTH_M / 2 + 0.04;

/** Radius of the whole circle, for keep-out tests: bench line plus the sitter's legs. */
export function seatingClusterRadiusM(config: SeatingConfig): number {
  return config.radiusM + BENCH_DEPTH_M / 2 + 0.9;
}

export type SeatingMeshKind = "box" | "cylinder";

/**
 * One primitive of the furniture, composer-centred. Box scales are full metres; a cylinder's
 * sx/sz are its DIAMETER (the primitive itself stays at radius 0.5 — see shared/dcl-disc).
 */
export interface SeatingPiece {
  id: string;
  mesh: SeatingMeshKind;
  x: number;
  y: number;
  z: number;
  /**
   * ★ Yaw is the ONLY rotation any piece carries. A raked back would need a second axis, and
   * the two renderers disagree on handedness — the Builder preview is Three.js (right-handed),
   * the scene is DCL (left-handed), so a pitch that leans back in one leans forward in the
   * other. The back is squared off instead, with a rail on top.
   */
  yawRad: number;
  sx: number;
  sy: number;
  sz: number;
  color: string;
  roughness: number;
  metalness: number;
  /**
   * Light this piece emits. Absent = an ordinary surface. The light strips are what make a
   * bench read as furniture from somewhere else rather than a park bench with the colour
   * changed, and after dark they are the only thing that says "sit here" from across a plaza.
   */
  emissive?: string;
  emissiveIntensity?: number;
  /**
   * ★ NO PHYSICS COLLIDER, EVER — only a pointer one, and only where noted.
   * The seated avatar's capsule stands at the seat anchor, which is INSIDE the slab and just
   * in front of the back panel. A blocking collider there does not make the bench solid, it
   * makes the explorer's character controller shove the sitter out of the pose the moment they
   * land on it. Same law as the paving and the ground cover: no invisible walls on the plot.
   */
  clickable: boolean;
}

/** Where one guest sits: the avatar root goes here, at paving level, facing `yawRad`. */
export interface SeatSlot {
  id: string;
  clusterId: string;
  x: number;
  z: number;
  yawRad: number;
}

export interface SeatingCluster {
  id: string;
  x: number;
  z: number;
  pieces: SeatingPiece[];
  seats: SeatSlot[];
}

export interface SeatingPlan {
  clusters: SeatingCluster[];
  seats: SeatSlot[];
  pieces: SeatingPiece[];
  /** Every primitive is a box or a low-segment cylinder; this is the whole cost. */
  triangles: number;
}

interface Finish {
  color: string;
  roughness: number;
  metalness: number;
}

interface StylePalette {
  /** Seat slab and back slats — the surfaces a guest reads as "the seat". */
  shell: Finish;
  /** Pedestal, base and rail — the structure the seat appears to float on. */
  frame: Finish;
  /** Multiplier on every light strip, so a pale bench does not blow out. */
  glow: number;
}


/**
 * Seating — bench circles you can actually sit on, and the poses that fit them.
 *
 * ★ THE POSE SETS THE HEIGHT, NOT THE MODEL. `scripts/emotes/build-seat-poses.ts` solves each
 * seated clip through forward kinematics until the grounded SOLE rests on the paving, and every
 * pose lands its hips within a couple of centimetres of SEAT_HIP_HEIGHT_M. The bench seat is
 * then modelled under the sitter's UNDERSIDE — see the note on BENCH_SEAT_TOP_M, which is where
 * the first version went wrong. Change a pose, re-run the script, copy the two numbers it
 * prints — never tune the bench to fix a pose.
 *
 * ★ THE AVATAR ROOT SITS UNDER THE HIPS. The clips keep the hips over the rig root and run the
 * legs forward, so `movePlayerTo` targets the seat pad's centre at ground level, not the feet.
 * A seat anchor is therefore the pad centre, and its yaw is the direction the sitter faces.
 *
 * ★ ONE PLANNER, TWO FRAMES. Like ground scatter, the layout is re-solved from the same config
 * in the Builder preview and in the scene runtime — it is never transported. Same config + same
 * plot ⇒ identical circles, so a republish does not move the benches under a returning guest.
 *
 * ★ Composer frame throughout (plot centre = 0,0). The runtime shifts by `composerToDcl`.
 */


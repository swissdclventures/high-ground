/** Triangles per primitive: a box is 12, a low-segment cylinder is 16 segments. */
const BOX_TRIANGLES = 12;
const CYLINDER_TRIANGLES = 16 * 4;

function rotate(x: number, z: number, yawRad: number): { x: number; z: number } {
  const s = Math.sin(yawRad);
  const c = Math.cos(yawRad);
  // Bench-local +Z is the direction the sitter faces; +X runs along the seat to their left.
  return { x: x * c + z * s, z: -x * s + z * c };
}

interface Lamp extends Finish {
  emissive: string;
  emissiveIntensity: number;
}

/** A light strip: the same primitive as everything else, just told to emit. */
function lamp(config: SeatingConfig, palette: StylePalette, intensity: number): Lamp {
  return {
    color: config.glowColor,
    roughness: 0.4,
    metalness: 0,
    emissive: config.glowColor,
    emissiveIntensity: intensity * palette.glow,
  };
}

type LocalPiece = Omit<SeatingPiece, "id" | "x" | "z" | "yawRad"> & { lx: number; lz: number };

/**
 * One bench, laid out in its own frame and then placed. Local +Z is where the sitter looks.
 *
 * ★ THE SLAB FLOATS ON ONE PEDESTAL. Four legs under the corners is the shape that made the
 * first version read as a park bench; a single centre column, a light strip under the seat and
 * a line on the paving read as something that was PUT there. It is also the cheaper shape:
 * eleven boxes, 132 triangles, no mesh, nothing baked into building.glb.
 */
function benchPieces(
  idPrefix: string,
  cx: number,
  cz: number,
  yawRad: number,
  config: SeatingConfig,
): SeatingPiece[] {
  const palette = STYLE_PALETTES[config.style];
  const seatTop = BENCH_SEAT_TOP_M;
  const slabY = seatTop - SEAT_SLAB_THICKNESS_M / 2;
  const slabBottom = seatTop - SEAT_SLAB_THICKNESS_M;
  const backZ = -BENCH_DEPTH_M / 2 + BACK_THICKNESS_M / 2;
  const finX = BENCH_LENGTH_M / 2 - 0.2;
  const baseH = 0.045;
  const pedestalH = slabBottom - baseH - 0.04;

  const local: LocalPiece[] = [
    // The seat itself.
    {
      lx: 0,
      y: slabY,
      lz: 0,
      sx: BENCH_LENGTH_M,
      sy: SEAT_SLAB_THICKNESS_M,
      sz: BENCH_DEPTH_M,
      mesh: "box",
      clickable: true,
      ...palette.shell,
    },
    // Light under the slab — the gap between this and the seat is what makes it look to float.
    {
      lx: 0,
      y: slabBottom - 0.032,
      lz: 0,
      sx: BENCH_LENGTH_M - 0.2,
      sy: 0.026,
      sz: BENCH_DEPTH_M - 0.14,
      mesh: "box",
      clickable: false,
      ...lamp(config, palette, 1.5),
    },
    // Single centre pedestal.
    {
      lx: 0,
      y: baseH + pedestalH / 2,
      lz: 0,
      sx: 0.34,
      sy: pedestalH,
      sz: 0.26,
      mesh: "box",
      clickable: true,
      ...palette.frame,
    },
    // Foot plate.
    {
      lx: 0,
      y: baseH / 2,
      lz: 0,
      sx: 0.66,
      sy: baseH,
      sz: 0.42,
      mesh: "box",
      clickable: true,
      ...palette.frame,
    },
    // A line of light on the paving, so the bench still has a footprint after dark.
    {
      lx: 0,
      y: 0.006,
      lz: 0,
      sx: BENCH_LENGTH_M - 0.86,
      sy: 0.012,
      sz: 0.055,
      mesh: "box",
      clickable: false,
      ...lamp(config, palette, 0.85),
    },
    // Two back fins instead of a full panel: the back reads as structure, not a wall.
    ...[-finX, finX].map((lx) => ({
      lx,
      y: seatTop + (BACK_TOP_M - seatTop) / 2,
      lz: backZ,
      sx: 0.065,
      sy: BACK_TOP_M - seatTop,
      sz: 0.09,
      mesh: "box" as const,
      clickable: true,
      ...palette.frame,
    })),
    // Two slats across them.
    ...[0.6, 0.715].map((y) => ({
      lx: 0,
      y,
      lz: backZ,
      sx: BENCH_LENGTH_M - 0.14,
      sy: 0.075,
      sz: BACK_THICKNESS_M / 2,
      mesh: "box" as const,
      clickable: true,
      ...palette.shell,
    })),
    // Top rail: what "arms on the back" rests on, and a second light line at arm height.
    {
      lx: 0,
      y: BACK_TOP_M - BACK_RAIL_M / 2,
      lz: backZ,
      sx: BENCH_LENGTH_M,
      sy: BACK_RAIL_M,
      sz: BACK_THICKNESS_M + 0.06,
      mesh: "box",
      clickable: true,
      ...palette.frame,
    },
    {
      lx: 0,
      y: BACK_TOP_M - BACK_RAIL_M - 0.012,
      lz: backZ,
      sx: BENCH_LENGTH_M - 0.1,
      sy: 0.018,
      sz: BACK_THICKNESS_M + 0.07,
      mesh: "box",
      clickable: false,
      ...lamp(config, palette, 1.1),
    },
  ];

  return local.map((p, i) => {
    const w = rotate(p.lx, p.lz, yawRad);
    return {
      id: `${idPrefix}_p${i}`,
      mesh: p.mesh,
      x: cx + w.x,
      y: p.y,
      z: cz + w.z,
      yawRad,
      sx: p.sx,
      sy: p.sy,
      sz: p.sz,
      color: p.color,
      roughness: p.roughness,
      metalness: p.metalness,
      ...(p.emissive ? { emissive: p.emissive, emissiveIntensity: p.emissiveIntensity } : {}),
      clickable: p.clickable,
    };
  });
}

/**
 * Seat anchors along one bench. The anchor is the pad centre — the avatar root goes there and
 * the seated legs run forward from it, which is exactly how the clips are authored.
 */
function benchSeats(idPrefix: string, clusterId: string, cx: number, cz: number, yawRad: number): SeatSlot[] {
  const out: SeatSlot[] = [];
  const first = -((SEATS_PER_BENCH - 1) / 2) * SEAT_PITCH_M;
  for (let i = 0; i < SEATS_PER_BENCH; i += 1) {
    // Sit a touch back of the pad centre: the hips belong over the rear half of the seat.
    const w = rotate(first + i * SEAT_PITCH_M, -0.04, yawRad);
    out.push({ id: `${idPrefix}_s${i}`, clusterId, x: cx + w.x, z: cz + w.z, yawRad });
  }
  return out;
}

/**
 * What stands in the middle of the circle.
 *
 * ★ A FLAT DISC IS NOT A CENTREPIECE. The first version was one squat cylinder, which in a dark
 * district renders as a black hole in the paving — "just a black circle". A ring of benches
 * needs something with HEIGHT at its focus, or it reads as three pieces of furniture that
 * happen to face each other. This is a beacon: a halo burnt into the paving, a plinth, a mast,
 * and a lantern floating clear of it.
 */
function centrepiecePieces(
  id: string,
  centreX: number,
  centreZ: number,
  config: SeatingConfig,
): SeatingPiece[] {
  const palette = STYLE_PALETTES[config.style];
  const at = (
    suffix: string,
    mesh: SeatingMeshKind,
    y: number,
    diameter: number,
    height: number,
    finish: Finish | Lamp,
    yawRad = 0,
  ): SeatingPiece => ({
    id: `${id}_hub_${suffix}`,
    mesh,
    x: centreX,
    y,
    z: centreZ,
    yawRad,
    sx: diameter,
    sy: height,
    sz: diameter,
    clickable: false,
    ...finish,
  });

  return [
    // Halo on the paving: the ring is what turns three benches into one place.
    at("halo", "cylinder", 0.005, config.radiusM * 1.12, 0.01, lamp(config, palette, 0.6)),
    at("plinth", "cylinder", 0.055, config.radiusM * 0.58, 0.11, palette.frame),
    at("disc", "cylinder", 0.118, config.radiusM * 0.46, 0.016, lamp(config, palette, 1.2)),
    at("mast", "box", 0.42, 0.12, 0.58, palette.frame),
    // Floating lantern, turned 45° so it catches the light on a corner instead of a face.
    at("lantern", "box", 0.86, 0.24, 0.24, lamp(config, palette, 1.8), Math.PI / 4),
  ];
}

/** One circle of benches, all facing the middle. */
export function seatingCluster(
  id: string,
  centreX: number,
  centreZ: number,
  spinRad: number,
  config: SeatingConfig,
): SeatingCluster {
  const pieces: SeatingPiece[] = [];
  const seats: SeatSlot[] = [];
  const n = Math.max(1, Math.round(config.benchesPerCluster));

  for (let i = 0; i < n; i += 1) {
    const theta = spinRad + (i / n) * Math.PI * 2;
    const bx = centreX + Math.sin(theta) * config.radiusM;
    const bz = centreZ + Math.cos(theta) * config.radiusM;
    // Facing the middle: the bench's local +Z points back at the centre.
    const yaw = theta + Math.PI;
    const prefix = `${id}_b${i}`;
    pieces.push(...benchPieces(prefix, bx, bz, yaw, config));
    seats.push(...benchSeats(prefix, id, bx, bz, yaw));
  }

  if (config.centrepiece) pieces.push(...centrepiecePieces(id, centreX, centreZ, config));

  return { id, x: centreX, z: centreZ, pieces, seats };
}


/**
 * Plan every circle on the plot. Deterministic from config + plot size, exactly like ground
 * scatter — the Builder preview and the scene runtime call this and get the same field.
 */
export function planSeating(args: {
  width: number;
  depth: number;
  config: SeatingConfig;
  exclusions?: readonly GroundScatterExclusion[];
}): SeatingPlan {
  const config = args.config;
  const empty: SeatingPlan = { clusters: [], seats: [], pieces: [], triangles: 0 };
  if (!config.enabled || config.clusters <= 0) return empty;

  const width = Math.max(0, args.width);
  const depth = Math.max(0, args.depth);
  const radius = seatingClusterRadiusM(config);
  const rng = makeGroundRng(`seating:${config.seed}`, width, depth);
  const points = scatterPoints({
    rng,
    count: Math.min(config.clusters, SEATING_MAX_CLUSTERS),
    halfW: width / 2 - config.edgeMarginM,
    halfD: depth / 2 - config.edgeMarginM,
    radius,
    minDist: Math.max(config.spacingM, radius * 2),
    exclusions: padExclusions(args.exclusions ?? [], config.clearanceM),
  });

  const clusters = points.map((p, i) => seatingCluster(`sc${i}`, p.x, p.z, rng() * Math.PI * 2, config));
  const pieces = clusters.flatMap((c) => c.pieces);
  return {
    clusters,
    seats: clusters.flatMap((c) => c.seats),
    pieces,
    triangles: pieces.reduce((n, p) => n + (p.mesh === "cylinder" ? CYLINDER_TRIANGLES : BOX_TRIANGLES), 0),
  };
}

/** True when a circle would land on top of a keep-out box. Exposed for the preview's warnings. */
export function seatingClusterBlocked(
  cluster: SeatingCluster,
  config: SeatingConfig,
  exclusions: readonly GroundScatterExclusion[],
): boolean {
  return exclusions.some((box) => circleHitsBox({ x: cluster.x, z: cluster.z }, seatingClusterRadiusM(config), box));
}
